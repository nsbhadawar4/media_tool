// Small builders keep the data readable. The answer is always added to the options, so it can
// never be missing; the engine shuffles options at play time.
const pick = (prompt: string, answer: string, wrong: string[], more: Partial<ChoiceQuestion> = {}): ChoiceQuestion => ({
  kind: 'choice',
  prompt,
  ...more,
  options: [answer, ...wrong],
  answer,
});
const pic = (visual: string, answer: string, wrong: string[], prompt: string) => pick(prompt, answer, wrong, { visual });
const read = (passage: string, prompt: string, answer: string, wrong: string[]) => pick(prompt, answer, wrong, { passage });
const blank = (sentence: string, answer: string, wrong: string[], explain?: string) =>
  pick('खाली जगह भरो।', answer, wrong, explain ? { sentence, explain } : { sentence });
const order = (prompt: string, items: string[]): OrderQuestion => ({ kind: 'order', prompt, items });
const word = (visual: string, tiles: string[], extra: string[]): BuildQuestion => ({ kind: 'build', prompt: 'अक्षर जोड़कर शब्द बनाओ।', visual, tiles, extra });
const sentence = (tiles: string[], extra: string[] = []): BuildQuestion => ({
  kind: 'build',
  prompt: 'शब्द जोड़कर सही वाक्य बनाओ।',
  tiles,
  ...(extra.length ? { extra } : {}),
  joiner: ' ',
});
const match = (prompt: string, pairs: [string, string][]): MatchQuestion => ({ kind: 'match', prompt, pairs });
const sort = (prompt: string, groups: Record<string, string[]>): SortQuestion => ({
  kind: 'sort',
  prompt,
  buckets: Object.keys(groups),
  items: Object.entries(groups).flatMap(([bucket, texts]) => texts.map((text) => ({ text, bucket }))),
});

